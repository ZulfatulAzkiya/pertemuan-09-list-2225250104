
# Mengakses Elemen List dengan Index dan Slicing

nilai = [80, 75, 90, 85, 70, 95]

print("Daftar nilai:", nilai)
print("Nilai pertama:", nilai[0])
print("Nilai ketiga:", nilai[2])
print("Nilai terakhir:", nilai[-1])
print("Tiga nilai pertama:", nilai[:3])
print("Nilai indeks 2 sampai 4:", nilai[2:5])