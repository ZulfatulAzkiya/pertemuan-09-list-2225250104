
# Manipulasi List

buah = ["Apel", "Jeruk", "Mangga"]

print("List awal:", buah)

buah.append("Pisang")
print("Setelah append:", buah)

buah.insert(1, "Anggur")
print("Setelah insert:", buah)

buah.remove("Jeruk")
print("Setelah remove:", buah)

buah.pop()
print("Setelah pop:", buah)

buah.sort()
print("Setelah sort:", buah)